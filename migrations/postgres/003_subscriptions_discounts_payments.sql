-- Jazz Recovery subscriptions and discount management.
-- Additive only: keeps existing users, devices, sessions and recovery tables intact.
CREATE TABLE IF NOT EXISTS subscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  trial_started_at TIMESTAMPTZ NOT NULL,
  trial_ends_at TIMESTAMPTZ NOT NULL,
  paid_started_at TIMESTAMPTZ,
  paid_ends_at TIMESTAMPTZ,
  status TEXT NOT NULL DEFAULT 'trialing' CHECK (status IN ('trialing','active','expired','complimentary')),
  last_payment_id TEXT UNIQUE,
  last_order_id TEXT UNIQUE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_subscriptions_trial_ends ON subscriptions(trial_ends_at);
CREATE INDEX IF NOT EXISTS idx_subscriptions_paid_ends ON subscriptions(paid_ends_at);

CREATE TABLE IF NOT EXISTS discount_codes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code_hash TEXT NOT NULL UNIQUE,
  code_hint TEXT NOT NULL,
  percent_off INTEGER NOT NULL CHECK (percent_off IN (10,20,50,100)),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  expires_at TIMESTAMPTZ,
  max_redemptions INTEGER,
  redemption_count INTEGER NOT NULL DEFAULT 0 CHECK (redemption_count >= 0),
  created_by TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_discount_codes_active ON discount_codes(active, expires_at);

CREATE TABLE IF NOT EXISTS discount_redemptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  discount_code_id BIGINT NOT NULL REFERENCES discount_codes(id),
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  subscription_id BIGINT REFERENCES subscriptions(id) ON DELETE SET NULL,
  percent_off INTEGER NOT NULL CHECK (percent_off IN (10,20,50,100)),
  amount_paise INTEGER NOT NULL CHECK (amount_paise BETWEEN 0 AND 49900),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(discount_code_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_discount_redemptions_user ON discount_redemptions(user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS payment_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  discount_code_id BIGINT REFERENCES discount_codes(id) ON DELETE SET NULL,
  provider_order_id TEXT NOT NULL UNIQUE,
  amount_paise INTEGER NOT NULL CHECK (amount_paise BETWEEN 1 AND 49900),
  currency TEXT NOT NULL DEFAULT 'INR' CHECK (currency = 'INR'),
  status TEXT NOT NULL DEFAULT 'created' CHECK (status IN ('created','paid','failed','cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  paid_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_payment_orders_user ON payment_orders(user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS payment_webhook_events (
  event_id TEXT PRIMARY KEY,
  event_type TEXT NOT NULL,
  processed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Existing accounts get a one-time migration-time trial record; no existing users are deleted.
INSERT INTO subscriptions(user_id,trial_started_at,trial_ends_at,status)
SELECT id, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP + INTERVAL '7 days', 'trialing'
FROM users
ON CONFLICT(user_id) DO NOTHING;
